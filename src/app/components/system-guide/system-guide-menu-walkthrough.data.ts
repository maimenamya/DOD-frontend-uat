import type {
  GuideSidebarGroup,
  GuideSidebarIcon,
  GuideWalkthroughBeat,
  GuideWalkthroughChapter,
} from './system-guide-walkthrough.data';

function mgmtBeat(
  title: string,
  icon: GuideSidebarIcon,
  children: Array<{ pin: number; label: string }>,
  doThis: string[],
  extra?: Pick<GuideWalkthroughBeat, 'warn'>,
): GuideWalkthroughBeat {
  const group: GuideSidebarGroup = {
    label: title,
    icon,
    children,
  };
  return {
    title,
    pathLabel: `แถบซ้าย → การจัดการ → ${title}`,
    doThis,
    sidebarPreview: {
      sectionLabel: 'การจัดการ',
      groups: [group],
    },
    ...extra,
  };
}

